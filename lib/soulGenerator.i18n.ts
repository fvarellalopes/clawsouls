const LOCALES: Record<Locale, TranslationDict> = { en, pt, es, fr, de, ja, zh };

/**
 * Get a translated string for the given locale and key.
 * Falls back to English if the key is missing in the target locale.
 * Supports {{variable}} interpolation.
 */
export function t(locale: Locale, key: string, vars?: Record<string, string>): string {
  const dict = LOCALES[locale] || en;
  let text = dict[key] ?? en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(`{{${k}}}`, v);
    }
  }
  return text;
}
